"""Markdown report export."""
from __future__ import annotations


def to_markdown(r: dict) -> str:
    m, ins, q = r["meta"], r["insights"], r["quality"]
    L: list[str] = []
    L.append(f"# RepoXray report — {r['repo']}\n")
    L.append(f"> {m.get('description') or ''}\n")
    L.append(f"**URL:** {r['url']}  ")
    L.append(f"**Type:** {r['project_type']}  ")
    L.append(f"**Health score:** {q['score']}/100 (grade {q['grade']})  ")
    if m.get("stars") is not None:
        L.append(f"**Stars:** {m['stars']} · **Forks:** {m.get('forks')} · **License:** {m.get('license') or '—'}\n")
    L.append("## Summary\n" + (ins.get("summary") or "") + "\n")
    if ins.get("purpose"):
        L.append("**Purpose:** " + ins["purpose"] + "\n")
    if ins.get("use_cases"):
        L.append("### Use cases\n" + "\n".join(f"- {u}" for u in ins["use_cases"]) + "\n")
    L.append("## How it works\n" + "\n".join(f"{i}. **{s['step']}** — {s['detail']}" for i, s in enumerate(ins.get("how_it_works", []), 1)) + "\n")
    if ins.get("architecture"):
        L.append("## Architecture\n" + ins["architecture"] + "\n")
    if r["diagrams"].get("architecture"):
        L.append("```mermaid\n" + r["diagrams"]["architecture"] + "\n```\n")
    L.append("## Tech stack\n| Technology | Category | Evidence |\n|---|---|---|")
    for t in r["stack"]:
        L.append(f"| {t['name']} | {t['category']} | {'; '.join(t['evidence'][:2])} |")
    L.append("\n## Languages\n" + ", ".join(f"{l['name']} ({l['percent']}%)" for l in r["languages"][:10]) + "\n")
    mt = r["metrics"]
    L.append(f"## Metrics\n- Files: {mt['files']}\n- Source files: {mt['source_files']} ({mt['source_loc']:,} LOC)\n"
             f"- Test files: {mt['test_files']} ({mt['test_loc']:,} LOC)\n- Avg complexity / file: {mt['avg_complexity']}\n")
    if r["entry_points"]:
        L.append("## Entry points\n" + "\n".join(f"- `{e['path']}` — {', '.join(e['reasons'])}" for e in r["entry_points"]) + "\n")
    c = r["commands"]
    L.append("## Getting started\n```bash")
    for k in ("install", "build", "test", "run", "docker"):
        for cmd in c.get(k, [])[:2]:
            L.append(f"{cmd}   # {k}")
    L.append("```\n")
    if ins.get("key_components"):
        L.append("## Key components\n" + "\n".join(f"- **{k['name']}** (`{k['path']}`) — {k['role']}" for k in ins["key_components"]) + "\n")
    if r["routes"]:
        L.append("## API routes\n| Method | Path | File |\n|---|---|---|")
        for x in r["routes"][:60]:
            L.append(f"| {x['method']} | `{x['path']}` | {x['file']}:{x['line']} |")
        L.append("")
    L.append("## Quality checks\n| Category | Score |\n|---|---|")
    for cat in q["categories"]:
        L.append(f"| {cat['name']} | {cat['score']} ({cat['passed']}/{cat['total']}) |")
    L.append("\n## Recommended improvements")
    for i in (ins.get("improvements") or []) + q["improvements"]:
        L.append(f"- **[{i.get('priority', '').upper()}] {i['title']}** — {i['detail']}")
    if r["security"]:
        L.append("\n## Security findings")
        for s in r["security"][:40]:
            L.append(f"- {s['severity'].upper()}: {s['type']} in `{s['file']}:{s['line']}`")
    outdated = [d for d in r["dependencies"]["dependencies"] if d.get("status") in ("major", "minor")]
    if outdated:
        L.append("\n## Outdated dependencies\n| Package | Current | Latest | Gap |\n|---|---|---|---|")
        for d in outdated[:50]:
            L.append(f"| {d['name']} | {d['spec']} | {d.get('latest')} | {d['status']} |")
    L.append("\n---\n_Generated by RepoXray_")
    return "\n".join(L)
